"""Inventory every NBM cycle of one day (core + qmd) for snow-related messages.

C:/miniforge3/envs/snow-wx/python.exe tools/nbm_inventory.py 20261107 [--out docs/nbm_inventory.md]

For each of the 24 cycles: max forecast hour per product, and for ASNOW / APCP /
SNOWLVL / SNOWLR the windows (hours), kinds (det / pct / prob), percentile levels,
exceedance thresholds and the forecast-hour range where each appears. Hours sampled:
every hour to f048, then every 3rd/6th hour as published (all files are listed, idx
fetched for hours <= 48 and every 6th hour after).
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import requests

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from pipeline.nbm.inventory import parse_idx  # noqa: E402

B = "https://noaa-nbm-grib2-pds.s3.amazonaws.com"
VARS = ("ASNOW", "APCP", "SNOWLVL", "SNOWLR")
S = requests.Session()
S.headers["User-Agent"] = "snow-wx inventory (+https://github.com/alexluke23/snow-wx)"


def list_hours(day, cyc, product):
    keys, token = [], None
    while True:
        params = {"list-type": 2, "prefix": f"blend.{day}/{cyc:02d}/{product}/"}
        if token:
            params["continuation-token"] = token
        t = S.get(f"{B}/", params=params, timeout=60).text
        keys += re.findall(rf"{product}\.f(\d{{3}})\.co\.grib2\.idx</Key>", t)
        m = re.search(r"<NextContinuationToken>([^<]+)", t)
        if not m:
            break
        token = m.group(1)
    return sorted({int(k) for k in keys})


def idx(day, cyc, product, h):
    r = S.get(f"{B}/blend.{day}/{cyc:02d}/{product}/blend.t{cyc:02d}z.{product}.f{h:03d}.co.grib2.idx", timeout=60)
    return parse_idx(r.text) if r.ok else []


def thr_in(value: str, var: str) -> str:
    """prob threshold string -> inches (ASNOW in m, APCP in mm)."""
    m = re.search(r">([0-9.eE+-]+)", value or "")
    if not m:
        return value
    x = float(m.group(1))
    inch = x * 39.3701 if var == "ASNOW" else x / 25.4 if var == "APCP" else x
    return f">{inch:.2f}".rstrip("0").rstrip(".")


def inventory(day: str):
    rows = {}
    for cyc in range(24):
        hours = {p: list_hours(day, cyc, p) for p in ("core", "qmd")}
        sample = hours                       # every published hour (window ends differ by cycle)
        jobs = [(p, h) for p, hs in sample.items() for h in hs]
        with ThreadPoolExecutor(16) as ex:
            msgs = dict(zip(jobs, ex.map(lambda a: idx(day, cyc, *a), jobs)))
        agg = defaultdict(lambda: {"hours": set(), "values": set()})
        for (p, h), ms in msgs.items():
            for m in ms:
                if m.var not in VARS:
                    continue
                win = "inst" if m.start is None else f"{m.end - m.start}h"
                if m.kind == "pct":
                    val = str(m.value)
                elif m.kind == "prob":
                    val = thr_in(m.value, m.var)
                else:
                    val = m.kind
                k = (p, m.var, m.level.replace(" above mean sea level", " MSL")[:12], win, m.kind)
                agg[k]["hours"].add(h)
                agg[k]["values"].add(val)
        rows[cyc] = {"max": {p: (max(hs) if hs else None) for p, hs in hours.items()}, "agg": agg}
        print(f"{cyc:02d}Z core max f{rows[cyc]['max']['core']} qmd max f{rows[cyc]['max']['qmd']} "
              f"({sum(len(v) for v in msgs.values())} msgs)", file=sys.stderr)
    return rows


def hr(hs):
    hs = sorted(hs)
    return f"f{hs[0]:03d}–f{hs[-1]:03d} ({len(hs)} h)"


def sort_vals(vals):
    def key(v):
        m = re.search(r"[0-9.]+", v)
        return (0, float(m.group())) if m else (1, v)
    return sorted(vals, key=key)


def markdown(day, rows) -> str:
    out = [f"# NBM inventory, {day[:4]}-{day[4:6]}-{day[6:]} (all 24 cycles)\n",
           "Generated by `tools/nbm_inventory.py`. Bucket `noaa-nbm-grib2-pds`; products per cycle: "
           "`core` (every cycle), `qmd` (00/06/12/18Z only), `text`. Hours: core files hourly to f048, "
           "3-hourly to f192, 6-hourly to f264; idx fetched for every published hour. "
           "Thresholds converted to inches (ASNOW m, APCP mm).\n",
           "## Max forecast hour per cycle\n", "| Cycle | core | qmd |", "|---|---|---|"]
    for c, r in rows.items():
        out.append(f"| {c:02d}Z | f{r['max']['core']} | {('f%d' % r['max']['qmd']) if r['max']['qmd'] else '—'} |")
    # group cycles with identical snow-message layouts
    sig = {c: tuple(sorted((k, frozenset(v["values"]), max(v["hours"]), min(v["hours"])) for k, v in r["agg"].items()))
           for c, r in rows.items()}
    groups = defaultdict(list)
    for c, s in sig.items():
        groups[s].append(c)
    out.append("\n## Snow-related messages by cycle layout\n")
    for s, cycles in groups.items():
        out.append(f"### Cycles {', '.join(f'{c:02d}Z' for c in cycles)}\n")
        out.append("| Product | Element | Level | Window | Kind | Values (percentiles / thresholds, in) | Hours |")
        out.append("|---|---|---|---|---|---|---|")
        agg = rows[cycles[0]]["agg"]
        for k in sorted(agg, key=lambda k: (k[0], k[1], k[4], int(re.sub(r"\D", "", k[3]) or 0))):
            v = agg[k]
            vals = ", ".join(sort_vals(v["values"]))
            out.append(f"| {k[0]} | {k[1]} | {k[2]} | {k[3]} | {k[4]} | {vals} | {hr(v['hours'])} |")
        out.append("")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("day")
    ap.add_argument("--out", default="docs/nbm_inventory.md")
    a = ap.parse_args()
    rows = inventory(a.day)
    notes = ""
    if Path(a.out).exists():          # keep hand-written notes below the marker
        prev = Path(a.out).read_text(encoding="utf-8")
        if "<!-- notes -->" in prev:
            notes = prev[prev.index("<!-- notes -->"):]
    nl = chr(10)
    Path(a.out).write_text(markdown(a.day, rows) + (nl + notes if notes else ""), encoding="utf-8")
    print("wrote", a.out, file=sys.stderr)
